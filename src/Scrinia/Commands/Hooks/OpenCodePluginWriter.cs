using Scrinia.Core.Process;

namespace Scrinia.Commands.Hooks;

/// <summary>
/// Generates the OpenCode plugin (<c>.opencode/plugin/scrinia.ts</c>) that delivers the per-turn
/// memory hint. OpenCode has no shell-hook channel, so this is its only path to the hint — but it
/// natively reads AGENTS.md (the baseline) and speaks MCP, so the plugin stays thin: it shells out
/// to <c>scri hint --client opencode</c> via the prompt-aware <c>experimental.chat.messages.transform</c>
/// hook and injects the bare payload. It does <b>not</b> reimplement restore (AGENTS.md covers the baseline).
///
/// <para>The plugin is a scrinia-owned whole file (overwrite on install, delete on uninstall). The
/// absolute <c>scri</c> path is baked in at generate-time (the plugin runs in a child process whose
/// PATH may not contain scrinia). The hook body is wrapped in <c>try/catch</c> and the API is
/// experimental — a future OpenCode change degrades to "no hint", never a crashed session.</para>
/// </summary>
public sealed class OpenCodePluginWriter : IAgentArtifactInstaller
{
    private const string MarkerLine = "// scrinia-managed: per-turn memory hint plugin";
    private readonly IProcessRunner _runner;

    public OpenCodePluginWriter(IProcessRunner? runner = null) => _runner = runner ?? new ProcessRunner();

    public string Name => "OpenCode plugin";

    public bool Applies(string workspaceRoot) => _runner.IsExecutableOnPath("opencode");

    public bool Install(string workspaceRoot)
    {
        string path = PluginPath(workspaceRoot);
        try
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, BuildPlugin());
            return true;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return false;
        }
    }

    public bool Uninstall(string workspaceRoot)
    {
        string path = PluginPath(workspaceRoot);
        if (!File.Exists(path)) return true;
        try
        {
            // Only delete if it's our generated file — never eat a user-authored scrinia.ts.
            if (File.ReadAllText(path).Contains(MarkerLine, StringComparison.Ordinal))
                File.Delete(path);
            return true;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return false;
        }
    }

    public HookStatus GetStatus(string workspaceRoot)
    {
        string path = PluginPath(workspaceRoot);
        if (!File.Exists(path)) return HookStatus.NotInstalled;

        string content = File.ReadAllText(path);
        if (!content.Contains(MarkerLine, StringComparison.Ordinal)) return HookStatus.NotInstalled;
        // Drift if the baked scri path no longer matches the current executable.
        return content.Contains(ScriPathLiteral(), StringComparison.Ordinal)
            ? HookStatus.Installed : HookStatus.Drift;
    }

    private static string PluginPath(string workspaceRoot) =>
        Path.Combine(workspaceRoot, ".opencode", "plugin", "scrinia.ts");

    /// <summary>
    /// The <c>scri</c> path as a double-quoted JS string literal for embedding. The plugin calls the
    /// exe directly (no shell), so we want the unquoted forward-slash path that
    /// <see cref="AgentHookSetup.ResolveScriExecutablePath"/> produces, with backslashes and quotes
    /// escaped for safe literal embedding (hand-rolled to stay trim-safe — no reflection-based JSON).
    /// </summary>
    private static string ScriPathLiteral()
    {
        string path = AgentHookSetup.ResolveScriExecutablePath().Trim('"')
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"");
        return $"\"{path}\"";
    }

    private static string BuildPlugin() =>
        $$"""
        {{MarkerLine}}
        // Generated by `scri setup` — edits will be overwritten. Re-run setup to regenerate.
        //
        // Pinned to OpenCode's experimental plugin API (experimental.chat.messages.transform).
        // Thin by design: all hint logic lives in the scrinia CLI; this only forwards the prompt
        // and injects the result. Defensive — any API drift or CLI failure degrades to "no hint".
        import { spawnSync } from "node:child_process"

        const SCRI = {{ScriPathLiteral()}}

        export const ScriniaHint = async () => ({
          "experimental.chat.messages.transform": async (_input: any, output: any) => {
            try {
              const messages = output?.messages
              if (!Array.isArray(messages) || messages.length === 0) return

              // Most recent user message text.
              let prompt = ""
              for (let i = messages.length - 1; i >= 0; i--) {
                const m = messages[i]
                if (m?.info?.role !== "user") continue
                const parts = Array.isArray(m?.parts) ? m.parts : []
                prompt = parts
                  .filter((p: any) => p?.type === "text")
                  .map((p: any) => p?.text ?? "")
                  .join("\n")
                  .trim()
                if (prompt) break
              }
              if (!prompt) return

              const res = spawnSync(SCRI, ["hint", "--client", "opencode"], {
                input: prompt,
                encoding: "utf8",
                timeout: 5000,
              })
              const hint = (res.stdout ?? "").trim()
              if (!hint) return

              // Inject as a trailing system message: seen by the model, not authored by the user.
              messages.push({ info: { role: "system" }, parts: [{ type: "text", text: hint }] })
            } catch {
              // Experimental API drift or CLI failure — never break the user's session.
            }
          },
        })
        """;
}
